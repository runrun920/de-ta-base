def import_questions():
    conn = sqlite3.connect(DB_FILE)
    cur = conn.cursor()

    print("登録処理を開始します...")
    
    count = 0
    for term_name, cat, sub_cat, q_text, c_a, c_b, c_c, c_d, c_ans, exp_beg, exp_adv, test_type in test_questions_data:
        # 1. terms テーブルへ登録（重複時はカテゴリ更新）
        cur.execute("""
        INSERT INTO terms (term_name, category, sub_category, official_def)
        VALUES (?, ?, ?, ?)
        ON CONFLICT(term_name) DO UPDATE SET category=?, sub_category=?
        """, (term_name, cat, sub_cat, exp_beg, cat, sub_cat))

        # 用語ID取得
        cur.execute("SELECT id FROM terms WHERE term_name = ?", (term_name,))
        term_id = cur.fetchone()[0]

        # 2. questions テーブルへ問題登録
        cur.execute("""
        INSERT INTO questions (term_id, question_text, choice_a, choice_b, choice_c, choice_d, correct_ans)
        VALUES (?, ?, ?, ?, ?, ?, ?)
        """, (term_id, q_text, c_a, c_b, c_c, c_d, c_ans))
        
        q_id = cur.lastrowid

        # 3. 解説データ登録
        cur.execute("INSERT INTO question_explanations_beginner (question_id, explanation) VALUES (?, ?)", (q_id, exp_beg))
        cur.execute("INSERT INTO question_explanations_advanced (question_id, explanation) VALUES (?, ?)", (q_id, exp_adv))

        count += 1

    conn.commit()
    conn.close()
    print(f"✅ 合計 {count} 問（事前10問・事後10問）を {DB_FILE} へ登録・更新しました！")

if __name__ == "__main__":
    import_questions()